def qa_slug(question: str) -> str:
    s = re.sub(r"[^\w\s가-힣]", "", question or "")
    s = re.sub(r"\s+", "-", s)
    return s[:60]


def infer_difficulty(question: str) -> str:
    advanced_terms = ["면역항암", "PSA", "CRP", "GLP-1", "임상", "상호작용"]
    intermediate_terms = ["약", "검사", "수치", "치료", "항생제", "수면제", "스타틴", "항암"]
    if any(t in question for t in advanced_terms):
        return "advanced"
    if any(t in question for t in intermediate_terms):
        return "intermediate"
    return "basic"


