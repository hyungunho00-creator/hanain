function plainLength(html) {
  return String(stripHtml(html || '')).replace(/\s+/g, ' ').trim().length
}

function applyBatch(payload, sourceName) {
  const questions = payload.questions || []
  const byId = new Map(questions.map((item) => [item.id, item]))
  const changed = []
  const missing = []

  for (const [id, upgrade] of Object.entries(UPGRADES)) {
    const item = byId.get(id)
    if (!item) {
      missing.push(id)
      continue
    }
    item.answer = upgrade.answer
    item.validatedAnswer = upgrade.answer
    item.qualityStatus = 'validated'
    item.sourceStatus = 'referenced'
    item.publicBodyMode = 'full'
    item.noindex = false
    item.reviewed = true
    item.reviewed_at = REVIEWED_AT
    item.reviewedAt = REVIEWED_AT
    item.rewrittenAt = REVIEWED_AT
    item.recoveryBatch = BATCH_ID
    item.reviewReason = '저품질 공개 제외 항목을 출처 기반 AEO형 본문으로 확장하고 상담 기록·위험 신호·성분 정보 분리 기준을 보강함.'
    if (upgrade.references) item.references = upgrade.references
    const validation = validateLegacyAnswer(item, upgrade.answer)
    changed.push({ id, chars: plainLength(upgrade.answer), indexable: isSearchIndexableQA(item), reason: validation.reason })
  }

  const failures = changed.filter((row) => !row.indexable || row.chars < 700)
  if (missing.length || failures.length) {
    throw new Error(`${sourceName}: missing=${missing.join(',')} failures=${JSON.stringify(failures)}`)
  }
  return changed
}

