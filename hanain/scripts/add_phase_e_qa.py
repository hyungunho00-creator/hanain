def main() -> int:
    if not QA_PATH.exists():
        print(f"qa.json 없음: {QA_PATH}", file=sys.stderr)
        return 1

    with open(QA_PATH, encoding="utf-8") as f:
        data = json.load(f)

    questions = data.get("questions", [])
    existing_ids = {q.get("id") for q in questions}

    added = 0
    skipped = 0
    for entry in QA_ENTRIES:
        if entry["id"] in existing_ids:
            skipped += 1
            continue
        questions.append(entry)
        added += 1

    data["questions"] = questions

    # 카테고리 count 갱신
    cat_counts = {}
    for q in questions:
        cat_counts[q.get("category")] = cat_counts.get(q.get("category"), 0) + 1
    for cat in data.get("categories", []):
        cat["count"] = cat_counts.get(cat["id"], cat.get("count", 0))

    with open(QA_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Phase E Q&A: added={added}, skipped={skipped}, total={len(questions)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
