function escapeHtml(value) {
  return String(value || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

function slugify(question) {
  return String(question || '')
    .replace(/[^\w\s가-힣]/g, '')
    .replace(/\s+/g, '-')
    .slice(0, 60)
}

function stripHtml(value) {
  return String(value || '').replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim()
}

function paragraphs(title, items) {
  return [
    `  <h4>${escapeHtml(title)}</h4>`,
    ...items.map((item) => `  <p>${escapeHtml(item)}</p>`),
  ].join('\n')
}

function bullets(title, items) {
  return [
    `  <h4>${escapeHtml(title)}</h4>`,
    '  <ul>',
    ...items.map((item) => `    <li>${escapeHtml(item)}</li>`),
    '  </ul>',
  ].join('\n')
}

function references(items) {
  return [
    '  <h4>참고한 공식·연구 자료</h4>',
    '  <ul>',
    ...items.map(
      (item) =>
        `    <li><a href="${escapeHtml(item.url)}" rel="nofollow noopener" target="_blank">${escapeHtml(item.title)}</a></li>`,
    ),
    '  </ul>',
  ].join('\n')
}

