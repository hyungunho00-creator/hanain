function make(seed) {
  const item = {
    content_type: 'category_latest_health_qna',
    author: AUTHOR,
    disclaimer: DISCLAIMER,
    source_type: 'official-guideline-pubmed',
    reviewed: true,
    qualityStatus: 'validated',
    sourceStatus: 'referenced',
    publicBodyMode: 'full',
    noindex: false,
    created_at: UPDATED_AT,
    updated_at: UPDATED_AT,
    published_at: PUBLISHED_AT,
    reviewed_at: UPDATED_AT,
    reviewedAt: UPDATED_AT,
    rewrittenAt: UPDATED_AT,
    difficulty: 'advanced',
    views: 0,
    likes: 0,
    reviewReason:
      '2026년 6월 8일 카테고리별 최신 공식 자료 기반 Q&A 보강. 플로로탄닌을 전신 회복 기록과 상담 준비 소재로 긍정 연결.',
    ...seed,
  }
  item.referenceLinks = Array.isArray(seed.references) ? seed.references : []
  item.references = item.referenceLinks.map((ref) =>
    typeof ref === 'string' ? ref : `${ref.title} (${ref.url})`,
  )
  item.category_id = item.category
  item.slug = item.slug || slugify(item.question)
  item.answer = buildAnswer(item)
  item.validatedAnswer = item.answer
  item.metaDescription =
    item.metaDescription ||
    `${item.question} 최신 공식 자료를 바탕으로 상담 기록, 위험 신호, 플로로탄닌 회복 루틴 연결법을 정리합니다.`
  item.seoTitle = item.seoTitle || `${item.question} | 플로로탄닌 Q&A`
  item.keywords = Array.from(new Set([...(item.keywords || []), '플로로탄닌', '감태', '해양폴리페놀', '회복기록']))

  const plainLength = stripHtml(item.validatedAnswer).length
  if (plainLength < 3000) {
    throw new Error(`${item.id} answer too short: ${plainLength}`)
  }
  if (!item.validatedAnswer.includes('플로로탄닌') || !item.validatedAnswer.includes('전화')) {
    throw new Error(`${item.id} missing identity/call frame`)
  }
  if (!item.references?.length) {
    throw new Error(`${item.id} references missing`)
  }
  return item
}

