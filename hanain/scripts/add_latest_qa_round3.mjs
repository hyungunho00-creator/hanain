function updateQaFile(filePath) {
  const payload = JSON.parse(fs.readFileSync(filePath, 'utf8'))
  const questions = Array.isArray(payload.questions) ? payload.questions : []
  const existingIds = new Map(questions.map((q, index) => [q.id, index]))
  const existingQuestions = new Map(questions.map((q) => [q.question, q.id]))

  let added = 0
  let updated = 0
  ITEMS.map(makeEntry).forEach((entry) => {
    const existingIndex = existingIds.get(entry.id)
    if (existingIndex !== undefined) {
      questions[existingIndex] = entry
      updated += 1
      return
    }
    if (existingQuestions.has(entry.question)) return
    questions.push(entry)
    existingIds.set(entry.id, questions.length - 1)
    existingQuestions.set(entry.question, entry.id)
    added += 1
  })

  payload.questions = questions
  for (const cat of payload.categories || []) {
    cat.count = questions.filter((q) => (q.category || q.category_id) === cat.id).length
  }

  fs.writeFileSync(filePath, `${JSON.stringify(payload, null, 2)}\n`, 'utf8')
  return { file: path.relative(ROOT, filePath), added, updated, total: questions.length }
}

