export function getHospitalInsightConfig(slug) {
  const config = hospitalInsightConfigs[slug];
  if (!config) throw new Error(`Missing hospital insight config: ${slug}`);
  return {
    related: relatedDefault,
    ...config,
    sourceLinks: (config.sources || ['kdca', 'nhis', 'food']).map((key) => commonSources[key]).filter(Boolean),
  };
}
